// Bundles each src/cli/<name>.ts into claude-plugin/scripts/<name>.mjs, one file with its dependencies inlined
// and, at the top, the copyright and licence of each inlined package.
// With --check, rebuilds in memory and fails if a committed bundle is missing, stale or has no source.
import { build } from 'esbuild';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, 'src', 'cli');
const OUT = join(ROOT, 'claude-plugin', 'scripts');
const check = process.argv.includes('--check');

const { outputFiles, metafile } = await build({
  absWorkingDir: ROOT, // keeps the path comments in bundles the same on every machine
  entryPoints: readdirSync(SRC)
    .filter((f) => f.endsWith('.ts'))
    .sort()
    .map((f) => join(SRC, f)),
  outdir: OUT,
  outExtension: { '.js': '.mjs' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  write: false,
  metafile: true,
  logLevel: 'warning',
});

const HEADER = [
  '// Built from src/cli by `npm run build`. Edit src/ and rebuild; do not edit this file.',
  "import { createRequire } from 'node:module';",
  'const require = createRequire(import.meta.url);',
];

/** The packages a bundle inlines, by name, from esbuild's list of its inputs. */
function packagesIn(output) {
  const names = Object.keys(output.inputs).map((input) => /^node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input)?.[1]);
  return [...new Set(names.filter((name) => name !== undefined))].sort();
}

/** A comment carrying an inlined package's copyright and licence, as its licence asks of every copy. */
function notice(name) {
  const dir = join(ROOT, 'node_modules', name);
  const file = readdirSync(dir).find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f));
  if (!file) throw new Error(`${name} has no licence file to carry into the bundle`);
  const { version, license } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const text = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim().replaceAll('*/', '* /');
  const lines = [`Includes ${name} ${version} (${license}):`, '', ...text.split('\n')];
  return ['/*', ...lines.map((line) => ` * ${line}`.trimEnd()), ' */'];
}

const bundles = outputFiles.map((file) => {
  const output = metafile.outputs[relative(ROOT, file.path).split(sep).join('/')];
  if (!output) throw new Error(`esbuild did not describe ${basename(file.path)}`);
  const header = [...HEADER, ...packagesIn(output).flatMap(notice)].join('\n');
  return { path: file.path, text: `${header}\n${file.text}` };
});

if (!check) {
  mkdirSync(OUT, { recursive: true });
  for (const file of bundles) writeFileSync(file.path, file.text);
  console.log(`Built ${bundles.map((f) => basename(f.path)).join(', ')}`);
} else {
  const built = new Set(bundles.map((f) => basename(f.path)));
  const stale = bundles
    .filter((f) => !existsSync(f.path) || readFileSync(f.path, 'utf8').replace(/\r\n/g, '\n') !== f.text)
    .map((f) => basename(f.path));
  const orphans = existsSync(OUT) ? readdirSync(OUT).filter((f) => f.endsWith('.mjs') && !built.has(f)) : [];
  if (stale.length || orphans.length) {
    if (stale.length) {
      console.error(`Out of date: ${stale.join(', ')}. Run npm run build and commit claude-plugin/scripts.`);
    }
    if (orphans.length) console.error(`No source in src/cli for: ${orphans.join(', ')}.`);
    process.exit(1);
  }
  console.log('Bundles match src/.');
}
